import test from 'node:test';
import assert from 'node:assert/strict';
import { randomUUID } from 'node:crypto';
import { promises as fs } from 'node:fs';
import path from 'node:path';
import os from 'node:os';
import { createBusinessLibraryService } from '../server/business-library.mjs';
import { createSupplyNetworkService } from '../server/supply-network.mjs';
import { museConversationFixture, actor, hash } from './fixtures/muse-conversation.mjs';

const command = () => ({ requestId: randomUUID() });
test('one persistent conversation: exact enterprise SKU, buyer consent, named merchant reply, original Muse receipt/file and acceptance', async t => {
  const directory = await fs.mkdtemp(path.join(os.tmpdir(), 'workspace-procurement-loop-'));
  t.after(() => fs.rm(directory, { recursive: true, force: true }));
  const f = await museConversationFixture(t, { diskDirectory: directory });
  const store = { read: () => f.store.read(), update: callback => f.change(callback) };
  const merchant = { ...actor, workspaceId: 'original-enterprise', role: 'admin' }, buyer = { subject: 'external-buyer-a', workspaceId: 'original-enterprise', role: 'buyer' };
  const foreign = { ...merchant, subject: 'another-merchant', nativeAgentId: 'another-session' };
  const library = createBusinessLibraryService({ store, artifacts: { download() { assert.fail('No product asset requested'); } } });
  const supply = () => createSupplyNetworkService({ store, workspaceId: merchant.workspaceId, merchantMember: subject => [merchant.subject, foreign.subject].includes(subject) });
  const skuId = randomUUID(), product = (await library.createProduct({ ...command(), name: 'Actual saved fixture product', skus: [{ id: skuId, code: 'ENTERPRISE-SKU-1' }] }, merchant)).product;
  let supplier = (await supply().createSupplier({ ...command(), displayName: 'Specified fixture merchant', country: 'China' }, merchant)).supplier;
  supplier = (await supply().bindMerchant(supplier.id, { ...command(), expectedRevision: supplier.revision, merchantSubject: merchant.subject, confirmed: true }, merchant)).supplier;
  await supply().publishSupplier(supplier.id, { ...command(), expectedRevision: supplier.revision, confirmed: true }, merchant);
  let listing = (await supply().createListing({ ...command(), supplierId: supplier.id, title: 'Public declared offer', sku: 'SUPPLIER-SKU-A', unitPrice: '2.50', currency: 'USD', moq: 100, leadDays: 10, incoterm: 'FOB' }, merchant)).listing;
  listing = (await supply().linkProduct(listing.id, { ...command(), expectedRevision: listing.revision, productId: product.id, expectedProductRevision: product.revision, skuId, confirmed: true }, merchant)).listing;
  await supply().publishListing(listing.id, { ...command(), expectedRevision: listing.revision, confirmed: true }, merchant);
  const input = { ...command(), listingId: listing.id, quantity: 200, destination: 'US', notes: 'Private buyer requirements' };
  const draft = (await supply().createInquiry(input, buyer)).inquiry;
  assert.equal(supply().inquiries(merchant).inquiries.length, 0);
  await f.restart();
  assert.equal((await supply().createInquiry(input, buyer)).inquiry.id, draft.id);
  assert.equal(store.read().supplyNetwork.inquiries.length, 1);
  const review = supply().reviewInquiry(draft.id, buyer), consent = { ...command(), expectedRevision: 1, expectedReviewHash: review.reviewHash, confirmed: true };
  await assert.rejects(supply().shareInquiry(draft.id, { ...consent, confirmed: false }, buyer), { code: 'SUPPLY_CONFIRMATION_REQUIRED' });
  await assert.rejects(supply().shareInquiry(draft.id, { ...consent, expectedReviewHash: '0'.repeat(64) }, buyer), { code: 'SUPPLY_STALE_CONSENT' });
  const shared = (await supply().shareInquiry(draft.id, consent, buyer)).inquiry;
  assert.equal((await supply().shareInquiry(draft.id, consent, buyer)).inquiry.id, draft.id);
  assert.throws(() => supply().inquiry(draft.id, foreign), { code: 'SUPPLY_NOT_FOUND' });
  assert.throws(() => supply().inquiry(draft.id, { ...buyer, subject: 'external-buyer-b' }), { code: 'SUPPLY_NOT_FOUND' });
  assert.throws(() => supply().inquiry(draft.id, { ...buyer, workspaceId: 'another-enterprise' }), { code: 'SUPPLY_WORKSPACE_REQUIRED' });
  // Preparing the original business request creates that exact original Session
  // mapping but still does not execute a model or grant private buyer material.
  const museInput = f.input('procurement-original-public-research');
  const prepared = await f.api().prepare(museInput);
  const attached = (await supply().attachInquiry(draft.id, { ...command(), expectedRevision: shared.revision, conversationId: actor.nativeAgentId, confirmed: true }, merchant)).inquiry;
  const replyBody = { ...command(), expectedRevision: attached.revision, expectedShareHash: review.reviewHash, content: 'Real persisted fixture merchant reply', confirmed: true };
  await assert.rejects(supply().replyInquiry(draft.id, replyBody, foreign), { code: 'SUPPLY_NOT_FOUND' });
  const replied = await supply().replyInquiry(draft.id, replyBody, merchant);
  await f.restart();
  assert.equal((await supply().replyInquiry(draft.id, replyBody, merchant)).reply.id, replied.reply.id);
  assert.equal(supply().inquiry(draft.id, buyer).inquiry.replies.length, 1);
  assert.equal(supply().conversationInquiries(actor.nativeAgentId, merchant).inquiries[0].id, draft.id);
  assert.equal(store.read().messages.filter(m => m.supplyInquiryId === draft.id).length, 2);
  const delegated = await f.approveAndDispatch(museInput);
  assert.equal(delegated.orderId, prepared.delegation.orderId);
  const attempt = (await f.call(delegated.orderId, 'claim', { requestId: 'original-fixture-claim' })).body;
  const file = await f.deliver(delegated.orderId, attempt);
  await f.api().refresh(delegated.orderId); await f.relay.reconcile();
  const returned = await f.api().get(delegated.orderId);
  assert.equal(returned.phase, 'result_returned'); assert.equal(returned.wake.observed, false);
  await f.api().accept(delegated.orderId, { confirmed: true, expectedReviewHash: delegated.reviewHash, receiptHash: returned.receiptHash });
  await f.restart();
  assert.equal((await f.api().get(delegated.orderId)).phase, 'enterprise_accepted');
  assert.deepEqual((await f.api().download(delegated.orderId, { artifactId: file.artifactId, version: 1, sha256: hash(file.bytes) })).bytes, file.bytes);
  await supply().revokeInquiry(draft.id, { ...command(), expectedRevision: replied.revision, confirmed: true }, buyer);
  assert.throws(() => supply().inquiry(draft.id, merchant), { code: 'SUPPLY_NOT_FOUND' });
  await assert.rejects(supply().replyInquiry(draft.id, { ...replyBody, requestId: randomUUID(), expectedRevision: replied.revision + 1 }, merchant), { code: 'SUPPLY_NOT_FOUND' });
  await f.restart();
  await supply().shareInquiry(draft.id, consent, buyer); // Historical receipt cannot restore access.
  assert.equal(supply().inquiry(draft.id, buyer).inquiry.share.status, 'revoked');
  assert.equal(supply().inquiry(draft.id, buyer).inquiry.shares[0].status, 'revoked');
  const currentSupplier = supply().suppliers().suppliers.find(row => row.id === supplier.id);
  await assert.rejects(supply().bindMerchant(supplier.id, { ...command(), expectedRevision: currentSupplier.revision, merchantSubject: foreign.subject, confirmed: true }, merchant), { code: 'SUPPLY_ORIGINAL_MERCHANT_REQUIRED' });
  assert.equal(supply().inquiries(merchant).inquiries.length, 0);
  assert.equal(store.read().workerOrders.length, 1); assert.equal(store.read().museTasks.length, 1);
  assert.equal(f.diskDiagnostics().durability, 'confirmed');
});
