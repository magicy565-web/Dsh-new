import { execFileSync } from "node:child_process";
import { createHash } from "node:crypto";
import { cpSync, existsSync, mkdirSync, readFileSync, rmSync, writeFileSync } from "node:fs";
import { dirname, join, resolve } from "node:path";
import { fileURLToPath } from "node:url";

const dir = dirname(fileURLToPath(import.meta.url));
const root = resolve(dir, "..");
const pluginDir = join(root, "integrations/dsh/dsh-buyer-magazine");
const dest = join(dir, "dist");
const downloads = join(dest, "downloads");
const pkg = JSON.parse(readFileSync(join(pluginDir, "package.json"), "utf8"));
if (pkg.name !== "dsh-buyer-magazine" || pkg.version !== "0.4.3") throw new Error("Unexpected plugin name/version");
const filename = pkg.name + "-" + pkg.version + ".tgz";
if (!existsSync(join(pluginDir, "index.js")) || !existsSync(join(pluginDir, "cordis.patch.yml"))) throw new Error("Plugin entry files missing");
rmSync(dest, { recursive: true, force: true });
mkdirSync(downloads, { recursive: true });
cpSync(join(dir, "index.html"), join(dest, "index.html"));
const packed = JSON.parse(execFileSync("npm", ["pack", pluginDir, "--pack-destination", downloads, "--ignore-scripts", "--json"], { cwd: root, encoding: "utf8", timeout: 120000 }));
if (packed.length !== 1 || packed[0].filename !== filename) throw new Error("Package mismatch");
const names = new Set((packed[0].files || []).map(f => f.path));
const required = ["index.js", "cordis.patch.yml", "src/apify.js", "src/authored-review.js", "src/browser-review.js", "skills/apify-ecommerce-intelligence/SKILL.md", "skills/editorial-magazine-design/SKILL.md", "skills/editorial-typography-system/SKILL.md", "skills/ai-media-kinetic-commerce/SKILL.md"];
for (const path of required) if (!names.has(path)) throw new Error("Missing packaged path: " + path);
const archive = readFileSync(join(downloads, filename));
if (archive.length < 4096) throw new Error("Suspiciously small package");
const sha256 = createHash("sha256").update(archive).digest("hex");
const manifest = { name: pkg.name, version: pkg.version, filename, bytes: archive.length, sha256, source: "https://github.com/magicy565-web/Dsh-new", buildDate: new Date().toISOString(), files: (packed[0].files || []).length, note: "Source package check only; not a live DSH/model/website end-to-end acceptance." };
writeFileSync(join(downloads, "manifest.json"), JSON.stringify(manifest, null, 2) + "\n");
writeFileSync(join(downloads, "SHA256SUMS.txt"), sha256 + "  " + filename + "\n");
console.log(JSON.stringify(manifest, null, 2));
