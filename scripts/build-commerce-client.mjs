import { build, transform } from 'esbuild';
import postcss from 'postcss';
import { readFile, writeFile, mkdir } from 'node:fs/promises';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = fileURLToPath(new URL('../', import.meta.url));
const plugin = join(root, 'integrations/dsh/dsh-commerce-network');
async function changed(path, value) {
  if (await readFile(path, 'utf8').catch(() => null) !== value) await writeFile(path, value);
}
const result = await build({
  absWorkingDir: root, entryPoints: [join(plugin, 'src/client.jsx')],
  write: false, bundle: true, format: 'cjs', platform: 'browser', target: 'es2022',
  minify: true, metafile: true, jsx: 'automatic',
  external: ['react', 'react-dom', 'react-dom/client', 'react/jsx-runtime'],
  define: { 'process.env.NODE_ENV': '"production"' }, legalComments: 'inline',
  banner: { js: '// Generated by npm run build:commerce-client. Edit src/, not this file.\nwindow.__ModuleLoader__.load({id:"dsh-commerce-network",factory(require){const module={exports:{}};' },
  footer: { js: 'return module.exports;}});' },
  plugins: [{ name: 'commerce-scoped-css', setup(builder) {
    builder.onLoad({ filter: /\.css$/ }, async args => {
      const sheet = postcss.parse(await readFile(args.path, 'utf8'));
      sheet.walkRules(rule => {
        if (rule.parent.type === 'atrule' && /keyframes$/.test(rule.parent.name)) return;
        rule.selectors = rule.selectors.map(selector => {
          if (/^\.cn(?:\b|[ .:#\[])/.test(selector)) return selector;
          if (selector === ':root') return '.cn';
          return `.cn ${selector}`;
        });
      });
      const css = (await transform(sheet.toString(), { loader: 'css', minify: true, target: 'chrome120' })).code;
      return { contents: `export default ${JSON.stringify(css)}`, loader: 'js' };
    });
  } }],
});
const output = result.outputFiles[0].text;
// A second React invalidates the native Host's hooks and contexts.
for (const input of Object.keys(result.metafile.inputs)) {
  if (/node_modules\/(?:react|react-dom)\//.test(input)) throw new Error(`Host-owned React was bundled: ${input}`);
}
await changed(join(plugin, 'client.js'), output);
const packages = new Set();
for (const input of Object.keys(result.metafile.inputs)) {
  const match = input.match(/node_modules\/((?:@[^/]+\/)?[^/]+)/);
  if (match) packages.add(match[1]);
}
const notices = ['Native DSH Commerce Network client. React and ReactDOM are supplied by the Host.'];
for (const name of [...packages].sort()) {
  const directory = join(root, 'node_modules', name);
  const metadata = JSON.parse(await readFile(join(directory, 'package.json'), 'utf8'));
  let license;
  for (const filename of ['LICENSE', 'LICENSE.md', 'LICENSE.txt', 'license']) {
    license = await readFile(join(directory, filename), 'utf8').catch(() => null);
    if (license) break;
  }
  if (!license) throw new Error(`Missing license for bundled package ${name}`);
  notices.push(`${name}@${metadata.version}\n${license.trimEnd()}`);
}
await changed(join(plugin, 'THIRD-PARTY-NOTICES.txt'), notices.join('\n\n---\n\n') + '\n');
console.log(`Commerce canvas: ${Math.round(Buffer.byteLength(output) / 1024)} KiB; React host-owned; scoped styles; ${packages.size} dependency notices.`);
