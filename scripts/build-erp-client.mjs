// Build one native DSH Client factory. React and the library stay host-owned.
import { build, transform } from 'esbuild';
import postcss from 'postcss';
import { readFile, writeFile } from 'node:fs/promises';
import { createRequire } from 'node:module';
import { dirname, join, relative } from 'node:path';
import { fileURLToPath } from 'node:url';
const root = fileURLToPath(new URL('../', import.meta.url));
const plugin = join(root, 'integrations/dsh/dsh-mini-erp');
const require = createRequire(import.meta.url);
const cssPath = require.resolve('@radix-ui/themes/styles.css');
const themeDir = dirname(cssPath);
// Include published styles for the components we ship, without the entire
// responsive layout utility catalog or unused component skins.
const components = postcss.parse(await readFile(join(themeDir,'components.css'),'utf8'));
components.walkRules(rule => {
  if (rule.parent.type === 'atrule' && /keyframes$/.test(rule.parent.name)) return;
  if (!/\.rt-(?:reset|BaseButton|BaseCard|Button|Card|Badge|TextField|TextArea|Table|ScrollArea|Progress|Spinner|Flex|Tooltip)/.test(rule.selector)) rule.remove();
});
const sheet = postcss.parse(await readFile(join(themeDir,'tokens.css'),'utf8') + '\n' + components.toString());
// Theme colors must never change the host's :root or another plugin's .dark.
sheet.walkRules(rule => {
  if (rule.parent.type === 'atrule' && /keyframes$/.test(rule.parent.name)) return;
  rule.selectors = rule.selectors.flatMap(selector => {
    if (selector.includes(':root')) return selector.replaceAll(':root', '.me');
    const scoped = `.me ${selector}`;
    return /^(?:\.radix-themes|\.light(?:-theme)?|\.dark(?:-theme)?|\[data-|:where\(\.radix-themes|:is\(\.dark)/.test(selector)
      ? [`.me${selector}`, scoped] : [scoped];
  });
});
const radixCss = (await transform(sheet.toString(), { loader: 'css', minify: true, target: 'chrome120' })).code;
const result = await build({
  absWorkingDir: root, entryPoints: [join(plugin,'src/client.js')], write: false, bundle: true,
  format: 'cjs', platform: 'browser', target: 'es2022', minify: true, metafile: true,
  external: ['react', 'react-dom', 'react/jsx-runtime', 'dsh-workspace-library'],
  define: {'process.env.NODE_ENV':'"production"'}, legalComments: 'inline', logLevel: 'error',
  banner: {js:'// Generated by npm run build:erp-client. Edit src/, not this file.\nwindow.__ModuleLoader__.load({id:"dsh-mini-erp",factory(require){const module={exports:{}};'},
  footer: {js:'return module.exports;}});'},
  plugins: [{name:'erp-inline-css',setup(build){
    build.onResolve({filter:/^erp:radix-css$/},()=>({path:'radix',namespace:'erp-css'}));
    build.onLoad({filter:/.*/,namespace:'erp-css'},()=>({contents:`export default ${JSON.stringify(radixCss)}`}));
    build.onLoad({filter:/\.css$/},async args=>({contents:`export default ${JSON.stringify((await transform(await readFile(args.path,'utf8'),{loader:'css',minify:true,target:'chrome120'})).code)}`,loader:'js'}));
  }}],
});
const output = result.outputFiles[0].text;
// Preserve byte-identical output/mtime when nothing changed (avoids native HMR reloads).
async function changed(path, value) {if(await readFile(path,'utf8').catch(()=>null)!==value)await writeFile(path,value);}
await changed(join(plugin,'client.js'),output);
const packages = new Set(['@radix-ui/themes']);
for (const path of Object.keys(result.metafile.inputs)) {
  const match = path.match(/node_modules\/((?:@[^/]+\/)?[^/]+)/);
  if(match) packages.add(match[1]);
}
const notices = ['Third-party UI code is bundled into client.js. React and ReactDOM are provided by DeepSeek Harness.\nInter font license: INTER-OFL.txt.'];
for(const name of [...packages].sort()) {
  const dir = join(root,'node_modules',name), pkg = JSON.parse(await readFile(join(dir,'package.json'),'utf8'));
  let license;
  for(const filename of ['LICENSE','LICENSE.md','LICENSE.txt','license']) {license = await readFile(join(dir,filename),'utf8').catch(()=>null);if(license)break;}
  if(!license)license = await readFile(join(plugin,'licenses',name.replaceAll('/','-')+'-LICENSE'),'utf8').catch(()=>null);
  if(!license)throw new Error(`Missing license for bundled dependency ${name}`);
  notices.push(`${name}@${pkg.version}\n${license}`);
}
await changed(join(plugin,'THIRD-PARTY-NOTICES.txt'),notices.join('\n\n---\n\n')+'\n');
console.log(`ERP Client: Radix Themes + Lucide, ${Math.round(Buffer.byteLength(output)/1024)} KiB, host React external, scoped inline CSS.`);
